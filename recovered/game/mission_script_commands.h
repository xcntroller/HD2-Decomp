inline const MissionScriptCommand* mission_script_command(std::string_view name) { //0042DE80 reverse lookup.
    for(std::size_t n=mission_script_commands.size();n;) {
        const auto& command=mission_script_commands[--n];
        if(MissionScriptLexer::equal(command.name,name))return &command;
    }
    return nullptr;
}
