// 006a8be0: only selector one chooses the alternate layout. All other values
// choose primary. Constructors clear settings, append all records, then apply
// dirty records using the CURRENT mode; they do not clear the input manager.
template<class Services>
void reset_binding_defaults(BindingConfiguration& configuration, BindingInputState& input,
                              Services& services, std::uint32_t layout) {
    clear_binding_settings(configuration);
    const auto& defaults = layout == 1 ? alternate_binding_defaults : primary_binding_defaults;
    for (const auto& record : defaults) configuration.settings.push_back(record);
    apply_dirty_bindings(configuration, input, services);
}

